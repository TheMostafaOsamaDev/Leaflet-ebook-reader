package com.leaflet.reader

import android.app.Activity
import android.content.Context
import android.content.Intent
import android.graphics.drawable.ColorDrawable
import android.net.Uri
import android.os.Bundle
import android.util.Log
import android.view.ActionMode
import android.view.Window
import androidx.activity.enableEdgeToEdge
import androidx.core.view.WindowInsetsCompat
import androidx.core.view.WindowInsetsControllerCompat

class MainActivity : TauriActivity() {
    override fun onCreate(savedInstanceState: Bundle?) {
        // Paint the launch window in the reader's own theme before anything
        // else. This window is what fills the screen from the moment the
        // launcher hands off until the webview's first frame — a few hundred
        // milliseconds — and the Material DayNight default paints it near
        // black, which is the black flash on startup. themes.xml sets a
        // sensible colour per OS DayNight; this narrows it to the theme the
        // reader actually picked, which is independent of that setting.
        applyRememberedLaunchBackground()

        enableEdgeToEdge()
        super.onCreate(savedInstanceState)

        // Tauri 2.11's tao 0.35 no longer initializes the `ndk_context` global
        // that our Rust JNI bridge (notify.rs) relies on. Bootstrap it here —
        // before the WebView/frontend mounts and fires the first Android
        // command — otherwise the app aborts with
        // "android context was not initialized". Safe to call once; guarded on
        // the Rust side.
        initRustNdkContext()

        // Suppress Android's floating text-selection toolbar
        // ("Copy / Select all / Share / Manage apps") so the app's
        // in-page SelectionPopover is the only UI shown when the
        // user highlights text. Selection itself still works — only
        // the system bar is hidden.
        //
        // We wrap the window's existing Window.Callback (delegating
        // every method via Kotlin `by`) and return null for floating
        // ActionMode requests. This intercepts the WebView's request
        // at the window level, which is the durable spot — the
        // generated RustWebView.kt would be a more direct override
        // point but it is regenerated by `tauri android dev`.
        window.callback = SuppressFloatingActionModeCallback(window.callback)
        Log.d("LeafletSheet", "installed SuppressFloatingActionModeCallback in onCreate")

        // Cold launch: stash any intent extra so consume_launch_intent
        // can drain it on frontend mount.
        intent?.let { rememberLaunchIntent(it) }
    }

    override fun onNewIntent(intent: Intent) {
        super.onNewIntent(intent)
        // Warm launch (singleTask): the running activity gets a new
        // intent (e.g., user tapped the notification while the app
        // was backgrounded). Update the stashed value so the frontend's
        // event listener fires the right side effect.
        rememberLaunchIntent(intent)
    }

    override fun onResume() {
        super.onResume()
        // Defensive: if anything in TauriActivity (or a plugin) reset
        // window.callback after onCreate, re-wrap it now so the
        // floating-action-mode suppression survives.
        if (window.callback !is SuppressFloatingActionModeCallback) {
            window.callback = SuppressFloatingActionModeCallback(window.callback)
        }
    }

    private fun rememberLaunchIntent(intent: Intent) {
        // A book handed to us by another app — "Open with" (VIEW), a single
        // share (SEND), or a multi-select share (SEND_MULTIPLE, e.g. a file
        // manager's "share 3 files"). Kept in its own field rather than
        // folded into pendingLaunchIntent, whose contract is the "queue"
        // sentinel.
        val bookPayload: String? = when (intent.action) {
            Intent.ACTION_VIEW -> intent.data?.toString()
            Intent.ACTION_SEND ->
                @Suppress("DEPRECATION")
                (intent.getParcelableExtra(Intent.EXTRA_STREAM) as? Uri)?.toString()
            Intent.ACTION_SEND_MULTIPLE -> {
                // The manifest's tauri-file-associations block (AUTO-
                // GENERATED, do not hand-edit) declares SEND_MULTIPLE
                // alongside SEND for every book MIME type, so this branch
                // is reachable, not defensive dead code.
                @Suppress("DEPRECATION")
                val uris = intent.getParcelableArrayListExtra<Uri>(Intent.EXTRA_STREAM)
                // CROSS-LANGUAGE CONTRACT: join with "\n", which cannot
                // appear inside a content:// URI, rather than emitting JSON
                // — pendingOpenUri stays a single String field so the JNI
                // side (notify.rs's read_pending_open_uri) doesn't change.
                // useIncomingFiles.ts on the frontend splits on the same
                // "\n" and pushes every part; the single-URI case (VIEW,
                // SEND) still works unchanged because splitting a string
                // with no "\n" yields exactly one element.
                uris?.takeIf { it.isNotEmpty() }?.joinToString("\n") { it.toString() }
            }
            else -> null
        }
        if (bookPayload != null) {
            pendingOpenUri = bookPayload
            return
        }

        val extra = intent.getStringExtra("riwaq.open") ?: return
        pendingLaunchIntent = extra
    }

    /** The reading theme's background, as stashed by the last
     *  `setBarAppearance` call. Falls back to the themes.xml colour on a first
     *  ever launch, where no theme has been chosen yet. */
    private fun launchBackgroundColor(): Int {
        val prefs = getSharedPreferences(LAUNCH_PREFS, Context.MODE_PRIVATE)
        return prefs.getInt(
            KEY_LAUNCH_BACKGROUND,
            resources.getColor(R.color.riwaq_launch_bg, theme),
        )
    }

    /** Repaint the window in the reading theme, so the frames between the
     *  splash screen and the webview's first paint are the app's own colour. */
    private fun applyRememberedLaunchBackground() {
        window.setBackgroundDrawable(ColorDrawable(launchBackgroundColor()))
    }

    /** wry hands us the webview the moment it is constructed, well before it
     *  has a document to paint. Left alone it renders black until first paint —
     *  which is the black screen at startup, and it sits *on top* of the window
     *  background so colouring the window alone does not fix it. */
    override fun onWebViewCreate(webView: android.webkit.WebView) {
        super.onWebViewCreate(webView)
        webView.setBackgroundColor(launchBackgroundColor())
    }

    /** Implemented in Rust (`notify.rs`). Initializes `ndk_context`'s global
     *  Activity + JavaVM handle so the JNI helpers in notify.rs can resolve the
     *  Android context. Must run before any Android command is invoked. */
    private external fun initRustNdkContext()

    companion object {
        /** Stashed launch-intent extra. Drained by Rust's
         *  consume_launch_intent. `@JvmField` emits a true static
         *  field (which JNI `GetStaticFieldID` expects); `@JvmStatic`
         *  would only generate accessor methods, not the field.
         *  `@Volatile` makes cross-thread reads see the latest write. */
        @JvmField
        @Volatile
        var pendingLaunchIntent: String? = null

        /** Stashed content:// (or file://) URI of a book another app asked
         *  us to open — or, for a SEND_MULTIPLE share, several URIs joined
         *  with "\n" (see rememberLaunchIntent). Drained by Rust's
         *  consume_open_uri, which hands the raw string to the frontend for
         *  splitting. Same @JvmField @Volatile reasoning as
         *  pendingLaunchIntent above: JNI's GetStaticFieldID needs a true
         *  static field, and the write lands on a different thread than the
         *  read. */
        @JvmField
        @Volatile
        var pendingOpenUri: String? = null

        /** SharedPreferences holding what the next cold launch needs to know
         *  about the in-app theme, before any JS has run. */
        private const val LAUNCH_PREFS = "riwaq.launch"
        private const val KEY_LAUNCH_BACKGROUND = "windowBackground"

        /** Set the status- and navigation-bar icon appearance to match
         *  the in-app reading theme, which is independent of the OS
         *  DayNight setting. `lightIcons` = true paints light (white)
         *  icons for a dark background; false paints dark icons for a
         *  light background. Called via JNI from Rust's
         *  set_status_bar_style command on every theme change.
         *
         *  `backgroundColor` is that theme's background as an opaque ARGB
         *  int. We only stash it here; `applyRememberedLaunchBackground`
         *  paints it on the NEXT launch, so the window standing in for the
         *  webview during startup is already the right colour instead of the
         *  Material DayNight default. Written synchronously-ish via apply()
         *  because the value only has to survive to the next process start.
         *
         *  Must touch the window on the UI thread — JNI calls arrive on
         *  an attached Rust thread, so we hop via runOnUiThread.
         *
         *  `@JvmStatic` so JNI sees a static method with a stable
         *  signature: (Landroid/app/Activity;ZI)V. */
        @JvmStatic
        fun setBarAppearance(
            activity: Activity,
            lightIcons: Boolean,
            backgroundColor: Int,
        ) {
            activity
                .getSharedPreferences(LAUNCH_PREFS, Context.MODE_PRIVATE)
                .edit()
                .putInt(KEY_LAUNCH_BACKGROUND, backgroundColor)
                .apply()

            activity.runOnUiThread {
                val window = activity.window
                val controller =
                    WindowInsetsControllerCompat(window, window.decorView)
                // isAppearance*Light* = true means "light background →
                // dark icons", which is the inverse of our lightIcons
                // (= light icons for a dark background) flag.
                controller.isAppearanceLightStatusBars = !lightIcons
                controller.isAppearanceLightNavigationBars = !lightIcons
            }
        }

        /** Hide or restore the status and navigation bars, for the reader's
         *  full-screen mode. Called via JNI from Rust's `set_immersive_mode`
         *  whenever the reader's own chrome is tapped away.
         *
         *  The app draws edge-to-edge (see `enableEdgeToEdge` in onCreate), so
         *  before this existed the system bars stayed painted over a reader
         *  that had already hidden its own: tapping into full screen left the
         *  clock and battery icons sitting on top of the first line of the
         *  page, with the text running underneath them.
         *
         *  BEHAVIOR_SHOW_TRANSIENT_BARS_BY_SWIPE is what keeps this from being
         *  a trap — the bars come back for a few seconds on an edge swipe, so
         *  the clock and the back gesture are always one swipe away, and they
         *  retreat again on their own without disturbing the page.
         *
         *  Must touch the window on the UI thread: JNI calls arrive on an
         *  attached Rust thread. Same reasoning as setBarAppearance above.
         *
         *  `@JvmStatic` so JNI sees a static method with a stable signature:
         *  (Landroid/app/Activity;Z)V. The descriptor here, the one in
         *  notify.rs and the -keep rule in proguard-rules.pro have to agree —
         *  see the note on setBarAppearance. */
        @JvmStatic
        fun setImmersiveMode(activity: Activity, immersive: Boolean) {
            activity.runOnUiThread {
                val window = activity.window
                val controller =
                    WindowInsetsControllerCompat(window, window.decorView)
                controller.systemBarsBehavior =
                    WindowInsetsControllerCompat
                        .BEHAVIOR_SHOW_TRANSIENT_BARS_BY_SWIPE
                if (immersive) {
                    controller.hide(WindowInsetsCompat.Type.systemBars())
                } else {
                    controller.show(WindowInsetsCompat.Type.systemBars())
                }
            }
        }
    }
}

/** Delegates every Window.Callback method to the wrapped instance,
 *  except `onWindowStartingActionMode` for floating ActionModes
 *  (Android's text-selection toolbar) which is short-circuited to
 *  null. Kotlin's `by delegate` forwards the ~25 methods of the
 *  Window.Callback interface so we don't have to spell them all
 *  out individually. */
private class SuppressFloatingActionModeCallback(
    private val delegate: Window.Callback,
) : Window.Callback by delegate {
    override fun onWindowStartingActionMode(
        callback: ActionMode.Callback?,
    ): ActionMode? {
        Log.d("LeafletSheet", "onWindowStartingActionMode (1-arg) — suppressing")
        return null
    }

    override fun onWindowStartingActionMode(
        callback: ActionMode.Callback?,
        type: Int,
    ): ActionMode? {
        Log.d(
            "LeafletSheet",
            "onWindowStartingActionMode (2-arg) type=$type — ${if (type == ActionMode.TYPE_FLOATING) "suppressing" else "passing through"}",
        )
        if (type == ActionMode.TYPE_FLOATING) return null
        return delegate.onWindowStartingActionMode(callback, type)
    }
}
